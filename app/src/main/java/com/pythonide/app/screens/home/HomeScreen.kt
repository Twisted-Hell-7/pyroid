@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun HomeScreen(
    onNavigateToEditor: (String?) -> Unit,
    onNavigateToREPL: () -> Unit,
    onNavigateToSettings: () -> Unit,
    onNavigateToFileManager: () -> Unit = {},
    onNavigateToProjects: () -> Unit = {},
    onNavigateToPackages: () -> Unit = {},
    viewModel: HomeViewModel = hiltViewModel()
) {
    val files by viewModel.files.collectAsState()
    val scrollBehavior = TopAppBarDefaults.exitUntilCollapsedScrollBehavior()

    Scaffold(
        modifier = Modifier.nestedScroll(scrollBehavior.nestedScrollConnection),
        topBar = {
            LargeTopAppBar(
                title = {
                    Column {
                        Text(
                            text = "Python IDE",
                            style = MaterialTheme.typography.headlineMedium,
                            fontWeight = FontWeight.Bold
                        )
                        Text(
                            text = "${files.size} files",
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                },
                actions = {
                    IconButton(onClick = onNavigateToPackages) {
                        Icon(Icons.Default.GridView, contentDescription = "Packages")
                    }
                    IconButton(onClick = onNavigateToSettings) {
                        Icon(Icons.Default.Settings, contentDescription = "Settings")
                    }
                },
                scrollBehavior = scrollBehavior,
                colors = TopAppBarDefaults.largeTopAppBarColors(
                    containerColor = MaterialTheme.colorScheme.surface,
                    scrolledContainerColor = MaterialTheme.colorScheme.surfaceContainer
                )
            )
        },
        floatingActionButton = {
            ExtendedFloatingActionButton(
                onClick = { onNavigateToEditor(null) },
                containerColor = MaterialTheme.colorScheme.primaryContainer,
                contentColor = MaterialTheme.colorScheme.onPrimaryContainer,
                shape = RoundedCornerShape(16.dp)
            ) {
                Icon(Icons.Default.Add, contentDescription = null)
                Spacer(modifier = Modifier.width(8.dp))
                Text("New File")
            }
        }
    ) { paddingValues ->
        AnimatedContent(
            targetState = files.isEmpty(),
            transitionSpec = {
                fadeIn(tween(300)) + slideInVertically(tween(300)) togetherWith
                fadeOut(tween(300)) + slideOutVertically(tween(300))
            },
            modifier = Modifier.padding(paddingValues),
            label = "content_transition"
        ) { isEmpty ->
            if (isEmpty) {
                EmptyState(
                    onNewFile = { onNavigateToEditor(null) },
                    modifier = Modifier.fillMaxSize()
                )
            } else {
                FileGrid(
                    files = files,
                    onFileClick = { fileId -> onNavigateToEditor(fileId) },
                    modifier = Modifier.fillMaxSize()
                )
            }
        }
    }
}

@Composable
private fun EmptyState(
    onNewFile: () -> Unit,
    modifier: Modifier = Modifier
) {
    Box(
        modifier = modifier,
        contentAlignment = Alignment.Center
    ) {
        Column(
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center,
            modifier = Modifier.padding(32.dp)
        ) {
            val scale by animateFloatAsState(
                targetValue = 1f,
                animationSpec = spring(
                    dampingRatio = Spring.DampingRatioMediumBouncy,
                    stiffness = Spring.StiffnessLow
